<template>
  <template v-if="order">
    <ContentWrap>
      <div class="mb-12px flex items-center justify-between">
        <div><el-button link type="primary" @click="router.push('/jsc/shipping/voyage')"><Icon icon="ep:arrow-left" class="mr-5px" />返回列表</el-button><span class="ml-12px text-18px font-bold">{{ order.no }}</span><el-tag class="ml-10px" :type="order.status === 90 ? 'danger' : 'success'">{{ statusText(order.status) }}</el-tag></div>
        <el-button v-if="order.status !== 90" type="danger" plain @click="voidVisible = true">作废</el-button>
      </div>
      <el-alert v-if="order.status === 90" type="error" :closable="false" class="mb-12px" :title="`已作废：${order.voidReason}｜${order.voidTime}。柜子已退回待出运，资料与费用记录保留。`" />
      <el-descriptions :column="4" border>
        <el-descriptions-item label="船名/航次" :span="2">{{ shipInfo?.voyage }}</el-descriptions-item>
        <el-descriptions-item label="航线" :span="2">{{ shipInfo?.route }}</el-descriptions-item>
        <el-descriptions-item label="提单号" :span="2">{{ blNos.join('、') || '-' }}</el-descriptions-item>
        <el-descriptions-item label="船司">{{ shipInfo?.carrier }}</el-descriptions-item>
        <el-descriptions-item label="在途天数">{{ transitDays }} 天</el-descriptions-item>
      </el-descriptions>
    </ContentWrap>

    <ContentWrap>
      <div class="mb-14px flex items-center justify-between"><b>1. 航程时间线</b><el-button type="primary" plain @click="trackShip"><Icon icon="ep:position" class="mr-5px" />查船位</el-button></div>
      <el-steps :active="stepActive" align-center finish-status="success">
        <el-step title="已出运" :description="order.shippedDate || ''" />
        <el-step title="已到港" :description="`${order.arrivedDate || ''}${operations.arrivedBy ? '｜' + operations.arrivedBy : ''}`" />
        <el-step title="已清关" :description="`${order.clearedDate || ''}${operations.clearedBy ? '｜' + operations.clearedBy : ''}`" />
      </el-steps>
      <div v-if="order.status === 10 || order.status === 20" class="mt-16px text-center"><el-button type="primary" @click="openAdvance">{{ order.status === 10 ? '标记已到港' : '标记已清关' }}</el-button><div class="mt-6px text-12px text-gray-500">只能标记相邻下一节点，已点亮节点不可回点</div></div>
    </ContentWrap>

    <ContentWrap>
      <div class="mb-12px font-bold">2. 柜子明细（实装数只读）</div>
      <el-table :data="containers" border>
        <el-table-column prop="containerNo" label="柜号" min-width="150" />
        <el-table-column prop="blNo" label="提单号" min-width="150" />
        <el-table-column label="柜型" width="100"><template #default="{ row }">{{ containerTypeText(row.containerType) }}</template></el-table-column>
        <el-table-column label="供应商数" width="100" align="center"><template #default="{ row }">{{ new Set(row.items.map((item: any) => item.supplierId)).size }}</template></el-table-column>
        <el-table-column label="SKU数" width="90" align="center"><template #default="{ row }">{{ new Set(row.items.map((item: any) => item.skuId)).size }}</template></el-table-column>
        <el-table-column label="实装数" width="110" align="right"><template #default="{ row }">{{ actualCount(row) }}</template></el-table-column>
        <el-table-column label="差异" min-width="220"><template #default="{ row }"><span v-if="diffItems(row).length" class="text-red-500">{{ diffItems(row).map((item: any) => `${skuOf(item.skuId)?.sku}：装${item.planCount}/实${item.actualCount}${item.diffRemark ? '（' + item.diffRemark + '）' : ''}`).join('；') }}</span><el-tag v-else type="success">无差异</el-tag></template></el-table-column>
      </el-table>
    </ContentWrap>

    <ContentWrap>
      <div class="mb-12px flex items-center justify-between"><b>3. 资料档案袋</b><span class="text-12px text-gray-500">虚线标签为系统自动归档；上传支持 PDF / 图片</span></div>
      <el-row :gutter="16">
        <el-col :span="15">
          <div v-for="summary in documentSummary" :key="summary.type" class="mb-12px border-b border-gray-100 pb-10px">
            <div class="mb-6px flex items-center gap-8px">
              <el-tag :type="summary.missing ? 'danger' : 'success'">{{ documentTypeText(summary.type) }} {{ summary.uploaded }}/{{ summary.expected }}</el-tag>
              <span v-if="summary.missing" class="text-12px text-red-500">缺失{{ summary.missingSuppliers.length ? '：' + summary.missingSuppliers.map((id: number) => supplierName(id)).join('、') : ` ${summary.missing} 项` }}</span>
            </div>
            <el-tag v-for="doc in documentsOfType(summary.type)" :key="doc.id" class="mr-6px mb-4px" :class="{ 'auto-doc': doc.autoGenerated }" :type="doc.autoGenerated ? 'info' : 'primary'" effect="plain">{{ doc.fileName }}<span v-if="doc.blNo">｜{{ doc.blNo }}</span></el-tag>
            <span v-if="!documentsOfType(summary.type).length" class="text-12px text-gray-400">暂无文件</span>
          </div>
          <div class="mb-6px"><el-tag type="info" effect="plain">系统自动归档</el-tag></div>
          <el-tag v-for="doc in autoDocuments" :key="doc.id" class="auto-doc mr-6px mb-4px" type="info" effect="plain">{{ doc.fileName }}</el-tag>
        </el-col>
        <el-col :span="9">
          <el-form label-width="90px" size="small">
            <el-form-item label="资料类型"><el-select v-model="uploadType" class="!w-1/1"><el-option v-for="type in 8" :key="type" :label="documentTypeText(type)" :value="type" /></el-select></el-form-item>
            <el-form-item label="提单号"><el-select v-model="uploadBlNo" clearable class="!w-1/1"><el-option v-for="no in blNos" :key="no" :label="no" :value="no" /></el-select></el-form-item>
            <el-form-item label="供应商"><el-select v-model="uploadSupplierId" clearable class="!w-1/1"><el-option v-for="item in suppliers" :key="item.id" :label="item.name" :value="item.id" /></el-select></el-form-item>
          </el-form>
          <el-upload drag :auto-upload="false" :show-file-list="false" accept=".pdf,image/*" :on-change="uploadDocument">
            <Icon icon="ep:upload-filled" class="mt-20px text-42px" />
            <div class="el-upload__text">拖拽文件到此处，或 <em>点击上传</em></div>
            <template #tip><div class="el-upload__tip">mock 上传后仅保存文件记录，不上传服务器</div></template>
          </el-upload>
        </el-col>
      </el-row>
    </ContentWrap>

    <ContentWrap>
      <div class="mb-12px font-bold">4. 本票船讯费用（点击行进入付款管理）</div>
      <el-table :data="feeRows" border @row-click="router.push('/jsc/payment/manage')">
        <el-table-column prop="paymentNo" label="付款单号" min-width="160" />
        <el-table-column prop="companyName" label="收款方" min-width="160" />
        <el-table-column prop="feeName" label="费用项" min-width="120" />
        <el-table-column prop="amount" label="金额" width="130" align="right"><template #default="{ row }">¥ {{ row.amount.toFixed(2) }}</template></el-table-column>
        <el-table-column label="付款状态" width="120" align="center"><template #default="{ row }"><el-tag :type="row.status === 30 ? 'success' : 'warning'">{{ paymentStatusText(row.status) }}</el-tag></template></el-table-column>
        <el-table-column label="已付/应付" width="160" align="right"><template #default="{ row }">{{ row.paidAmount.toFixed(2) }} / {{ row.totalAmount.toFixed(2) }}</template></el-table-column>
      </el-table>
      <el-empty v-if="!feeRows.length" description="本票船讯暂无费用记录" />
    </ContentWrap>
  </template>
  <ContentWrap v-else v-loading="loading"><el-empty v-if="!loading" description="出运单不存在" /></ContentWrap>

  <Dialog v-model="advanceVisible" :title="order?.status === 10 ? '标记已到港' : '标记已清关'" width="450">
    <el-form label-width="90px"><el-form-item label="节点日期" required><el-date-picker v-model="advanceDate" type="date" value-format="YYYY-MM-DD" class="!w-1/1" /></el-form-item></el-form>
    <template #footer><el-button type="primary" @click="submitAdvance">确 认</el-button><el-button @click="advanceVisible = false">取 消</el-button></template>
  </Dialog>
  <Dialog v-model="voidVisible" title="作废出运单" width="520">
    <el-alert type="warning" :closable="false" class="mb-12px" title="作废后柜子退回待出运、实装数解锁；资料档案袋与费用记录不动。" />
    <el-form label-width="90px"><el-form-item label="作废原因" required><el-input v-model="voidReason" type="textarea" :rows="4" placeholder="必填，说明转错或需纠正的原因" /></el-form-item></el-form>
    <template #footer><el-button type="danger" @click="submitVoid">确认作废</el-button><el-button @click="voidVisible = false">取 消</el-button></template>
  </Dialog>
</template>

<script setup lang="ts">
import { useRoute, useRouter } from 'vue-router'
import { ContainerApi, ShipInfoApi, ShippingBaseApi, VoyageApi } from '@/api/jsc/shipping'
import type { ContainerVO, PaymentVO, ServiceProviderVO, ShipInfoVO, SkuVO, SupplierVO, VoyageOrderVO } from '@/api/jsc/types'

defineOptions({ name: 'JscVoyageDetail' })
const route = useRoute()
const router = useRouter()
const message = useMessage()
const loading = ref(false)
const order = ref<VoyageOrderVO>()
const shipInfo = ref<ShipInfoVO>()
const containers = ref<ContainerVO[]>([])
const operations = ref<{ arrivedBy?: string; clearedBy?: string }>({})
const fees = ref<PaymentVO[]>([])
const documentSummary = ref<any[]>([])
const skus = ref<SkuVO[]>([])
const suppliers = ref<SupplierVO[]>([])
const providers = ref<ServiceProviderVO[]>([])
const advanceVisible = ref(false)
const advanceDate = ref('')
const voidVisible = ref(false)
const voidReason = ref('')
const uploadType = ref(1)
const uploadBlNo = ref()
const uploadSupplierId = ref()
const documentNames: Record<number, string> = { 1: '提单', 2: '报关单', 3: '商检报告', 4: '发票', 5: '清关放行单', 6: '电放保函', 7: '费用确认单', 8: '采购合同', 9: '系统生成资料' }
const statusText = (status: number) => ({ 10: '已出运', 20: '已到港', 30: '已清关', 90: '已作废' }[status] || status)
const stepActive = computed(() => order.value?.status === 30 ? 3 : order.value?.status === 20 ? 2 : 1)
const blNos = computed(() => [...new Set(containers.value.map((item) => item.blNo).filter(Boolean))] as string[])
const transitDays = computed(() => {
  if (!order.value?.shippedDate) return 0
  const end = order.value.arrivedDate ? new Date(order.value.arrivedDate).getTime() : Date.now()
  return Math.max(0, Math.ceil((end - new Date(order.value.shippedDate).getTime()) / 86400000))
})
const skuOf = (id: number) => skus.value.find((item) => item.id === id)
const supplierName = (id: number) => suppliers.value.find((item) => item.id === id)?.name || id
const containerTypeText = (type: number) => ({ 1: '20尺', 2: '40尺', 3: '40HQ', 4: '45尺' }[type] || type)
const actualCount = (row: ContainerVO) => row.items.reduce((sum, item) => sum + (item.actualCount ?? 0), 0)
const diffItems = (row: ContainerVO) => row.items.filter((item) => item.actualCount !== undefined && item.actualCount !== item.planCount)
const documentTypeText = (type: number) => documentNames[type]
const documentsOfType = (type: number) => order.value?.documents.filter((item) => item.type === type) || []
const autoDocuments = computed(() => order.value?.documents.filter((item) => item.type === 9 || item.autoGenerated) || [])
const paymentStatusText = (status: number) => ({ 10: '待审核', 20: '待付款', 25: '部分付款', 30: '已付款', 15: '等退款', 90: '已作废' }[status] || status)
const feeRows = computed(() => fees.value.flatMap((payment) => payment.details.map((detail) => ({
  paymentNo: payment.no,
  companyName: providers.value.find((item) => item.id === payment.companyId)?.name || suppliers.value.find((item) => item.id === payment.companyId)?.name || payment.companyId,
  feeName: detail.feeName,
  amount: detail.amount,
  status: payment.status,
  paidAmount: payment.paidAmount,
  totalAmount: payment.totalAmount
}))))

const loadData = async () => {
  loading.value = true
  try {
    const id = Number(route.params.id)
    const data = await VoyageApi.getVoyage(id)
    order.value = data
    if (!data) return
    const [ship, allContainers, ops, feeData, summary] = await Promise.all([
      ShipInfoApi.getShipInfo(data.shipInfoId),
      ContainerApi.getContainerList(),
      VoyageApi.getOperations(id),
      VoyageApi.getFees(data.shipInfoId),
      VoyageApi.getDocumentSummary(id)
    ])
    shipInfo.value = ship
    containers.value = allContainers.filter((item) => data.containerIds.includes(item.id))
    operations.value = ops
    fees.value = feeData
    documentSummary.value = summary
  } finally {
    loading.value = false
  }
}
const openAdvance = () => {
  const now = new Date()
  advanceDate.value = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`
  advanceVisible.value = true
}
const submitAdvance = async () => {
  if (!advanceDate.value || !order.value) return message.error('请选择节点日期')
  await VoyageApi.advance(order.value.id, advanceDate.value)
  advanceVisible.value = false
  message.success('航程节点已点亮，日期与操作人已记录')
  await loadData()
}
const trackShip = () => {
  if (!blNos.value.length) return message.warning('暂无提单号，无法查船位')
  window.open(`https://www.maersk.com/tracking/${encodeURIComponent(blNos.value[0])}`, '_blank')
}
const uploadDocument = async (file: any) => {
  if (!order.value) return
  await VoyageApi.uploadDocument(order.value.id, uploadType.value, file.name, uploadBlNo.value, uploadSupplierId.value)
  message.success(`${documentTypeText(uploadType.value)}已上传归档`)
  await loadData()
}
const submitVoid = async () => {
  if (!voidReason.value.trim()) return message.error('作废原因必填')
  await ElMessageBox.confirm('作废后不可作为正常出运单继续流转，确认作废？', '二次确认', { type: 'warning' })
  await VoyageApi.void(order.value!.id, voidReason.value.trim())
  voidVisible.value = false
  voidReason.value = ''
  message.success('出运单已作废，柜子已退回待出运')
  await loadData()
}
onMounted(async () => {
  const options = await ShippingBaseApi.getOptions()
  skus.value = options.skus
  suppliers.value = options.suppliers
  providers.value = options.serviceProviders
  await loadData()
})
</script>

<style scoped>
.auto-doc { border-style: dashed; }
</style>
